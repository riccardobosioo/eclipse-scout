  const italianKeys = Object.keys(messages.it).sort();
  const spanishKeys = Object.keys(messages.es).sort();
  if (italianKeys.length !== spanishKeys.length
    || italianKeys.some(function (key, index) { return key !== spanishKeys[index]; })) {
    throw new Error('Eclipse Scout i18n catalogues are out of sync.');
  }

  function supportedLanguage() {
    const override = new URLSearchParams(window.location.search).get('lang');
    if (override === 'es' || override === 'it') return override;
    const preferences = window.navigator.languages && window.navigator.languages.length
      ? Array.from(window.navigator.languages)
      : [window.navigator.language || 'it'];
    for (const preference of preferences) {
      const code = String(preference || '').toLowerCase().split('-')[0];
      if (code === 'es' || code === 'it') return code;
    }
    return 'it';
  }

  const language = supportedLanguage();
  document.documentElement.lang = language;

  function t(key, variables) {
    let value = messages[language][key];
    if (value === undefined) value = messages.it[key];
    if (value === undefined) return key;
    const source = variables && typeof variables === 'object' ? variables : {};
    return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(source, name) ? String(source[name]) : match;
    });
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (element) {
      element.textContent = t(element.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(function (element) {
      element.innerHTML = t(element.dataset.i18nHtml);
    });
    ['aria-label', 'title', 'placeholder', 'content'].forEach(function (attribute) {
      const dataName = 'data-i18n-' + attribute;
      scope.querySelectorAll('[' + dataName + ']').forEach(function (element) {
        element.setAttribute(attribute, t(element.getAttribute(dataName)));
      });
    });
  }

  function formatNumber(value, maximumFractionDigits) {
    if (!Number.isFinite(Number(value))) return String(value);
    const digits = Number.isFinite(maximumFractionDigits) ? maximumFractionDigits : 0;
    return new Intl.NumberFormat(language === 'es' ? 'es-ES' : 'it-IT', {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(Number(value));
  }

  window.EclipseI18n = Object.freeze({
    apply: apply,
    formatNumber: formatNumber,
    googleMapsLanguage: function () { return language === 'es' ? 'es' : 'it'; },
    keys: Object.freeze(italianKeys.slice()),
    language: language,
    locale: language === 'es' ? 'es-ES' : 'it-IT',
    t: t,
  });

